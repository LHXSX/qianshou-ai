def _statute(
    sid: str,
    title: str,
    art: str,
    excerpt: str,
    keywords: list[str] | None = None,
    *,
    date: str = "",
    publisher: str = "国家法律法规数据库",
    url: str = _FLK,
) -> dict:
    return {
        "sourceId": sid,
        "type": "statute",
        "title": title,
        "articleOrCase": art,
        "url": url,
        "excerpt": excerpt,
        "publisher": publisher,
        "effectiveDate": date,
        "keywords": keywords or [],
    }


