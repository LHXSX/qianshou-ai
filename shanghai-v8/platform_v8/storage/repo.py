    @staticmethod
    def join_race(s: Session, shard_id: str, racer_worker_id: str) -> bool:
        """把空闲节点加入 RUNNING/DISPATCHED 片的竞速池 (不改 owner · 先到先得)。"""
        sh = ShardRepo.by_id(s, shard_id)
        if sh is None:
            return False
        if sh.status not in (
            ShardStatus.DISPATCHED, ShardStatus.RUNNING, ShardStatus.LEASED,
        ):
            return False
        racer = str(racer_worker_id)
        if not racer:
            return False
        if racer in ShardRepo.race_workers_of(sh):
            return False  # 已在竞速
        md = dict(sh.metadata or {})
        racers = [str(x) for x in (md.get("race_workers") or []) if x]
        if racer not in racers:
            racers.append(racer)
        md["race_workers"] = racers
        md["race_enabled"] = True
        result = s.execute(
            update(shards_t)
            .where(shards_t.c.id == shard_id)
            .where(shards_t.c.status.in_([
                ShardStatus.DISPATCHED.value,
                ShardStatus.RUNNING.value,
                ShardStatus.LEASED.value,
            ]))
            .values(metadata=md)
        )
        return result.rowcount > 0

    @staticmethod
    def drop_race_worker(s: Session, shard_id: str, worker_id: str) -> bool:
        """竞速失败者 / 失败节点退出 race_workers。"""
        sh = ShardRepo.by_id(s, shard_id)
        if sh is None:
            return False
        md = dict(sh.metadata or {})
        wid = str(worker_id)
        racers = [str(x) for x in (md.get("race_workers") or []) if x and str(x) != wid]
        md["race_workers"] = racers
        s.execute(
            update(shards_t).where(shards_t.c.id == shard_id).values(metadata=md)
        )
        return True

    @staticmethod
    def mark_done(s: Session, shard_id: str, *, output_ref: str | None = None,
                  elapsed_ms: int | None = None,
                  expected_worker_id: str | None = None,
                  expected_attempt: int | None = None,
                  verification: dict[str, Any] | None = None) -> bool:
        """2026-05-25 NCE patch: 加 expected_worker_id CAS · 防老 worker 残留 result
        2026-06-24 自愈加固: 加状态守卫 · 只允许 DISPATCHED/RUNNING/LEASED → DONE,
        防止迟到的成功帧把已 FAILED/CANCELLED 的 shard 翻成 DONE(错误发奖/状态错乱)。
        2026-07-22 · 竞速: expected 在 race_workers 内也允许 · 先到先得并把 owner 切到胜者。
        """
        sh = ShardRepo.by_id(s, shard_id)
        if sh is None:
            # QS-20：只留痕，不改控制流。
            ShardRepo._record_result_rejected(
                "shard_missing", shard_id=shard_id, shard=None,
                expected_worker_id=expected_worker_id, expected_attempt=expected_attempt,
            )
            return False
        if expected_worker_id is not None:
            ew = str(expected_worker_id)
            owner = str(sh.worker_id) if sh.worker_id else ""
            if ew != owner and ew not in ShardRepo.race_workers_of(sh):
                # QS-20：迟到/被回收后的结果在这里被 CAS 拒绝——以前是静默 False，现在记一条。
                ShardRepo._record_result_rejected(
                    "worker_mismatch", shard_id=shard_id, shard=sh,
                    expected_worker_id=ew, expected_attempt=expected_attempt,
                )
                return False

        values: dict[str, Any] = {
            "status": ShardStatus.DONE.value,
            "output_ref": output_ref,
            "completed_at": datetime.utcnow(),
            "elapsed_ms": elapsed_ms,
            "progress_at": None,
            "lease_by_node": None,
            "lease_expires_at": None,
            # 重试成功后清掉前次失败遗留，避免 DONE 分片仍显示失败原因。
            "error": "",
            "failure_class": None,
        }
        # 竞速胜者记为 owner · 便于结算/展示
        if expected_worker_id is not None:
            values["worker_id"] = str(expected_worker_id)
        if verification is not None:
            metadata = dict(sh.metadata or {})
            metadata["result_verification"] = dict(verification)
            # artifact issuance is single-use: a retry cannot replay it.
            metadata.pop("result_upload_issuance", None)
            metadata.pop("result_upload_issuances", None)
            values["metadata"] = metadata

        statement = (
            update(shards_t)
            .where(shards_t.c.id == shard_id)
            .where(shards_t.c.status.in_([
                ShardStatus.DISPATCHED.value,
                ShardStatus.RUNNING.value,
                ShardStatus.LEASED.value,
            ]))
        )
        if expected_worker_id is not None and str(expected_worker_id) == str(sh.worker_id):
            statement = statement.where(shards_t.c.worker_id == str(expected_worker_id))
        if expected_attempt is not None:
            statement = statement.where(shards_t.c.attempts == int(expected_attempt))
        result = s.execute(statement.values(**values))
        if result.rowcount <= 0:
            # QS-20：状态守卫（已 DONE/FAILED/CANCELLED）或 worker/attempts 并发变化把这帧挡掉了。
            ShardRepo._record_result_rejected(
                "state_guard", shard_id=shard_id, shard=sh,
                expected_worker_id=expected_worker_id, expected_attempt=expected_attempt,
            )
        return result.rowcount > 0

    @staticmethod
    def _record_result_rejected(
        reason: str,
        *,
        shard_id: str,
        shard: Any,
        expected_worker_id: str | None,
        expected_attempt: int | None,
    ) -> None:
        """QS-20 · mark_done 拒绝一条结果帧时留痕：lifecycle 事件 result_rejected（进程内计数 + INFO +
        we_audit `lifecycle.result_rejected`，detail 带原始 workload_id / shard_id / worker_id）。
        绝不抛出：留痕失败只打 ERROR，mark_done 的返回值与以前完全一致。"""
        try:
            from platform_v8.services.observability import record_lifecycle_event, redact_identifier
            extra: dict[str, Any] = {"reason": reason}
            if shard is not None:
                status = getattr(shard, "status", None)
                extra["shard_status"] = str(getattr(status, "value", status) or "")
                extra["shard_attempts"] = int(getattr(shard, "attempts", 0) or 0)
                extra["owner"] = redact_identifier(shard.worker_id) if shard.worker_id else None
            record_lifecycle_event(
                "result_rejected",
                workload_id=(shard.workload_id if shard is not None else None),
                shard_id=shard_id,
                worker_id=expected_worker_id,
                attempt=expected_attempt,
                reason_code=reason,
                outcome="rejected",
                extra=extra,
            )
        except Exception:
            import logging
            logging.getLogger(__name__).error(
                "mark_done result_rejected 留痕失败 · shard=%s reason=%s", shard_id, reason, exc_info=True,
            )

