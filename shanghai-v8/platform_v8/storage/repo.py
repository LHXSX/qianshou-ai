def _row_dict(row: Any) -> dict[str, Any] | None:
    return dict(row._mapping) if row is not None else None


class ResultVerificationRepo:
    """Durable, attempt-scoped result verification state.

    All mutations are guarded by the current state/retry count and intentionally
    leave commit/rollback ownership with the caller.
    """

    PENDING = "PENDING"
    LEASED = "LEASED"
    RETRY_SCHEDULED = "RETRY_SCHEDULED"
    SUCCEEDED = "SUCCEEDED"
    FAILED = "FAILED"

    @staticmethod
    def get(s: Session, shard_id: str, attempt: int) -> dict[str, Any] | None:
        row = s.execute(
            select(result_verifications_t).where(
                result_verifications_t.c.shard_id == str(shard_id),
                result_verifications_t.c.attempt == int(attempt),
            )
        ).one_or_none()
        return _row_dict(row)

    @staticmethod
    def current(s: Session, shard_id: str) -> dict[str, Any] | None:
        row = s.execute(
            select(result_verifications_t)
            .where(result_verifications_t.c.shard_id == str(shard_id))
            .order_by(result_verifications_t.c.attempt.desc())
            .limit(1)
        ).one_or_none()
        return _row_dict(row)

    @staticmethod
    def by_workload_for_update(
        s: Session, workload_id: str,
    ) -> list[dict[str, Any]]:
        rows = s.execute(
            select(result_verifications_t)
            .where(result_verifications_t.c.workload_id == str(workload_id))
            .order_by(
                result_verifications_t.c.shard_id,
                result_verifications_t.c.attempt,
            )
            .with_for_update()
        ).all()
        return [dict(row._mapping) for row in rows]

    @staticmethod
    def upsert(
        s: Session,
        *,
        shard_id: str,
        workload_id: str,
        worker_id: str | None,
        attempt: int,
        requested_policy: str,
        verifier_key: str,
        content_sha256: str | None = None,
        artifact: dict[str, Any] | None = None,
        evidence: dict[str, Any] | None = None,
        max_retries: int = 3,
    ) -> dict[str, Any]:
        """Create or refresh immutable request context without resetting state."""
        policy = str(requested_policy or "").strip()
        key = str(verifier_key or "").strip()
        if not policy or not key:
            raise ValueError("requested_policy and verifier_key are required")
        attempt_value = int(attempt)
        retries_value = int(max_retries)
        if attempt_value < 0 or retries_value < 0:
            raise ValueError("attempt and max_retries must be non-negative")
        digest = str(content_sha256 or "").strip().lower() or None
        if digest is not None and (
            len(digest) != 64 or any(ch not in "0123456789abcdef" for ch in digest)
        ):
            raise ValueError("content_sha256 must be 64 lowercase hex characters")

        now = datetime.now(timezone.utc)
        identity = (
            result_verifications_t.c.shard_id == str(shard_id),
            result_verifications_t.c.attempt == attempt_value,
        )
        worker_value = str(worker_id) if worker_id is not None else None
        worker_matches = (
            result_verifications_t.c.worker_id.is_(None)
            if worker_value is None
            else result_verifications_t.c.worker_id == worker_value
        )
        digest_matches = (
            result_verifications_t.c.content_sha256.is_(None)
            if digest is None
            else result_verifications_t.c.content_sha256 == digest
        )
        contract_matches = (
            result_verifications_t.c.workload_id == str(workload_id),
            worker_matches,
            result_verifications_t.c.requested_policy == policy,
            result_verifications_t.c.verifier_key == key,
            digest_matches,
            result_verifications_t.c.max_retries == retries_value,
        )
        refresh_values: dict[str, Any] = {
            "updated_at": now,
        }
        if artifact is not None:
            refresh_values["artifact"] = dict(artifact)
        if evidence is not None:
            refresh_values["evidence"] = dict(evidence)

        refreshed = s.execute(
            update(result_verifications_t)
            .where(*identity)
            .where(*contract_matches)
            .where(result_verifications_t.c.state == ResultVerificationRepo.PENDING)
            .values(**refresh_values)
        )
        if refreshed.rowcount <= 0:
            values = {
                **refresh_values,
                "shard_id": str(shard_id),
                "workload_id": str(workload_id),
                "worker_id": worker_value,
                "attempt": attempt_value,
                "requested_policy": policy,
                "verifier_key": key,
                "content_sha256": digest,
                "artifact": dict(artifact or {}),
                "evidence": dict(evidence or {}),
                "state": ResultVerificationRepo.PENDING,
                "retry_count": 0,
                "max_retries": retries_value,
                "next_retry_at": now,
                "error": "",
                "created_at": now,
            }
            try:
                with s.begin_nested():
                    s.execute(insert(result_verifications_t).values(**values))
            except IntegrityError:
                # A concurrent creator won the unique(shard_id, attempt) race.
                pass

        persisted = ResultVerificationRepo.get(s, str(shard_id), attempt_value)
        if persisted is None:
            raise RuntimeError("result verification upsert did not persist a row")
        expected_contract = {
            "workload_id": str(workload_id),
            "worker_id": worker_value,
            "requested_policy": policy,
            "verifier_key": key,
            "content_sha256": digest,
            "max_retries": retries_value,
        }
        actual_contract = {
            key: (
                str(persisted[key])
                if key in {"workload_id", "worker_id"} and persisted[key] is not None
                else persisted[key]
            )
            for key in expected_contract
        }
        if actual_contract != expected_contract:
            # LAN / 重派：允许覆盖未终态 verification 合同（quarantine→artifact）
            st = str(persisted.get("state") or "")
            if st in {
                ResultVerificationRepo.PENDING,
                ResultVerificationRepo.RETRY_SCHEDULED,
                ResultVerificationRepo.LEASED,
                getattr(ResultVerificationRepo, "FAILED", "failed"),
            }:
                s.execute(
                    update(result_verifications_t)
                    .where(result_verifications_t.c.shard_id == str(shard_id))
                    .where(result_verifications_t.c.attempt == attempt_value)
                    .values(**{k: values[k] for k in (
                        "workload_id", "worker_id", "requested_policy", "verifier_key",
                        "content_sha256", "artifact", "evidence", "state",
                        "retry_count", "max_retries", "next_retry_at", "error",
                    ) if k in values})
                )
                persisted = ResultVerificationRepo.get(s, str(shard_id), attempt_value)
            else:
                raise ValueError("result verification contract conflicts with existing attempt")
        return persisted

    @staticmethod
    def claim_due_retries(
        s: Session,
        *,
        limit: int = 20,
        lease_seconds: int = 120,
        now: datetime | None = None,
    ) -> list[dict[str, Any]]:
        """Claim due or expired verification work with FOR UPDATE SKIP LOCKED."""
        claimed_at = now or datetime.now(timezone.utc)
        lease_until = claimed_at + timedelta(seconds=max(1, int(lease_seconds)))
        due = or_(
            and_(
                result_verifications_t.c.state.in_([
                    ResultVerificationRepo.PENDING,
                    ResultVerificationRepo.RETRY_SCHEDULED,
                ]),
                or_(
                    result_verifications_t.c.next_retry_at.is_(None),
                    result_verifications_t.c.next_retry_at <= claimed_at,
                ),
            ),
            and_(
                result_verifications_t.c.state == ResultVerificationRepo.LEASED,
                result_verifications_t.c.lease_until.is_not(None),
                result_verifications_t.c.lease_until <= claimed_at,
            ),
        )
        rows = s.execute(
            select(result_verifications_t.c.id)
            .where(due)
            .where(
                result_verifications_t.c.retry_count
                <= result_verifications_t.c.max_retries
            )
            .order_by(
                result_verifications_t.c.next_retry_at,
                result_verifications_t.c.updated_at,
            )
            .limit(max(1, min(int(limit), 500)))
            .with_for_update(skip_locked=True)
        ).all()
        claimed_ids: list[int] = []
        for row in rows:
            result = s.execute(
                update(result_verifications_t)
                .where(result_verifications_t.c.id == row.id)
                .where(due)
                .values(
                    state=ResultVerificationRepo.LEASED,
                    lease_until=lease_until,
                    updated_at=claimed_at,
                )
            )
            if result.rowcount > 0:
                claimed_ids.append(int(row.id))
        if not claimed_ids:
            return []
        claimed = s.execute(
            select(result_verifications_t)
            .where(result_verifications_t.c.id.in_(claimed_ids))
            .order_by(result_verifications_t.c.updated_at, result_verifications_t.c.id)
        ).all()
        return [dict(row._mapping) for row in claimed]

