def _clear_attempt_bindings(metadata: Any) -> dict[str, Any]:
    """Remove single-attempt state and retain issued object keys for reaping."""
    cleaned = dict(metadata or {})
    issuances = cleaned.pop("result_upload_issuances", None)
    legacy = cleaned.pop("result_upload_issuance", None)
    orphaned = list(cleaned.get("orphaned_result_artifacts") or [])
    candidates = list((issuances or {}).values()) if isinstance(issuances, dict) else []
    if isinstance(legacy, dict):
        candidates.append(legacy)
    seen_keys = {str(item.get("object_key") or "") for item in orphaned if isinstance(item, dict)}
    for issuance in candidates:
        if not isinstance(issuance, dict):
            continue
        object_key = str(issuance.get("object_key") or "")
        if not object_key or object_key in seen_keys:
            continue
        # Only persist keys generated by record_result_upload_issuance.  The
        # lifecycle reaper will delete these after a short grace period.
        orphaned.append({
            "object_key": object_key,
            "not_before": int(time.time()) + 300,
        })
        seen_keys.add(object_key)
    if orphaned:
        cleaned["orphaned_result_artifacts"] = orphaned[-32:]
    cleaned.pop("result_verification", None)
    cleaned.pop("race_workers", None)
    cleaned.pop("race_enabled", None)
    return cleaned

