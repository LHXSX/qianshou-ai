    @staticmethod
    def touch_progress(
        s: Session,
        shard_id: str,
        *,
        expected_worker_id: str,
        expected_attempt: int,
        lease_seconds: int | None = None,
        now: datetime | None = None,
    ) -> bool:
        """持久化当前 assignment 的可信进度，并为 PULL 续租。

        worker/attempt/status 均为 CAS 条件；迟到帧无法复活或续租已重派分片。
        首次合法进度可把 DISPATCHED/LEASED 原子推进到 RUNNING。
        """
        progress_now = now or datetime.now(timezone.utc)
        if progress_now.tzinfo is None:
            progress_now = progress_now.replace(tzinfo=timezone.utc)
        lease_now = progress_now.astimezone(timezone.utc).replace(tzinfo=None)
        worker = str(expected_worker_id)
        active_owner = or_(
            and_(
                shards_t.c.status.in_([
                    ShardStatus.DISPATCHED.value,
                    ShardStatus.RUNNING.value,
                ]),
                shards_t.c.worker_id == worker,
            ),
            and_(
                shards_t.c.status == ShardStatus.LEASED.value,
                shards_t.c.lease_by_node == worker,
            ),
        )
        values: dict[str, Any] = {
            "status": ShardStatus.RUNNING.value,
            "progress_at": progress_now,
            "started_at": func.coalesce(shards_t.c.started_at, lease_now),
            "exec_attempts": case(
                (
                    shards_t.c.status.in_([
                        ShardStatus.DISPATCHED.value,
                        ShardStatus.LEASED.value,
                    ]),
                    func.coalesce(shards_t.c.exec_attempts, 0) + 1,
                ),
                else_=shards_t.c.exec_attempts,
            ),
        }
        if lease_seconds is not None:
            values["lease_expires_at"] = lease_now + timedelta(
                seconds=max(1, int(lease_seconds))
            )
        # LEASED rows do not have worker_id until the first ack/progress.
        values["worker_id"] = worker
        result = s.execute(
            update(shards_t)
            .where(shards_t.c.id == shard_id)
            .where(shards_t.c.attempts == int(expected_attempt))
            .where(active_owner)
            .values(**values)
        )
        return result.rowcount > 0

