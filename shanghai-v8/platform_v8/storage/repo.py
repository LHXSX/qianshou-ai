class LedgerError(Exception):
    pass


class IdempotentConflict(LedgerError):
    """idempotent_key 已存在 · 写入被阻止 (业务可视为成功 · 因为之前写过了)"""
    pass


class LedgerRepo:
    """账本 · append-only · idempotent_key 防重复"""

    @staticmethod
    def write(s: Session, entry: LedgerEntry) -> LedgerEntry:
        """
        写一条 LedgerEntry · idempotent_key 冲突会抛 IdempotentConflict

        caller 处理:
            try:
                LedgerRepo.write(s, entry)
            except IdempotentConflict:
                # 已存在 · 业务视作成功
                pass
        """
        if not entry.idempotent_key:
            raise LedgerError("idempotent_key 必填 (防重复)")
        values = {
            "id": entry.id,
            "account_id": entry.account_id,
            "type": entry.type.value,
            "amount": entry.amount,
            "currency": entry.currency,
            "workload_id": entry.workload_id,
            "shard_id": entry.shard_id,
            "basis": getattr(entry, "basis", None),
            "worker_id": getattr(entry, "worker_id", None),
            "idempotent_key": entry.idempotent_key,
            "note": entry.note,
            "metadata": entry.metadata,
            "created_at": entry.created_at,
        }
        # The unique index is the authoritative concurrency guard.  Do the
        # insert in a SAVEPOINT so a losing concurrent caller can continue its
        # outer settlement transaction and refresh its balance cache.
        try:
            with s.begin_nested():
                s.execute(insert(ledger_t).values(**values))
                s.flush()
        except IntegrityError as exc:
            existing = s.execute(
                select(ledger_t.c.id).where(
                    ledger_t.c.idempotent_key == entry.idempotent_key
                )
            ).one_or_none()
            if existing is not None:
                raise IdempotentConflict(entry.idempotent_key) from exc
            raise
        return entry

    @staticmethod
    def sum_balance(s: Session, account_id: int) -> Decimal:
        """从 ledger SUM 出余额 (单一真相源)"""
        total = s.execute(
            select(func.coalesce(func.sum(ledger_t.c.amount), 0))
            .where(ledger_t.c.account_id == account_id)
        ).scalar_one()
        return Decimal(str(total))

    @staticmethod
    def list_by_account(s: Session, account_id: int,
                        *, type: str | None = None,
                        limit: int = 50, offset: int = 0) -> list[dict]:
        stmt = (
            select(ledger_t).where(ledger_t.c.account_id == account_id)
            .order_by(ledger_t.c.created_at.desc())
            .limit(limit).offset(offset)
        )
        if type:
            stmt = stmt.where(ledger_t.c.type == type)
        rows = s.execute(stmt).all()
        return [dict(r._mapping) for r in rows]

    @staticmethod
    def list_by_workload(s: Session, workload_id: str) -> list[dict]:
        rows = s.execute(
            select(ledger_t).where(ledger_t.c.workload_id == workload_id)
            .order_by(ledger_t.c.created_at)
        ).all()
        return [dict(r._mapping) for r in rows]


# ── helper: dataclass → dict (内部用) ─────────────────
def _dc_asdict(obj: Any) -> dict:
    """dataclass → dict · 嵌套 Enum 转 .value"""
    import dataclasses as _dc
    if _dc.is_dataclass(obj):
        d = _dc.asdict(obj)
        # 把里面的 Enum 字段转 .value (asdict 不会自动转)
        return _convert_enums(d)
    return obj or {}


def _convert_enums(obj):
    from enum import Enum
    if isinstance(obj, dict):
        return {k: _convert_enums(v) for k, v in obj.items()}
    if isinstance(obj, list):
        return [_convert_enums(x) for x in obj]
    if isinstance(obj, Enum):
        return obj.value
    if isinstance(obj, Decimal):
        return str(obj)
    return obj
