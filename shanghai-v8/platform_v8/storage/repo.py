    @staticmethod
    def bulk_update_heartbeat(s: Session, buffer: dict) -> int:
        """
        M1 扩容 · 批量回写心跳 (heartbeat.flush_hb_buffer 调 · 2026-06-02)

        buffer: {worker_id: {"load","active_shards","last_seen"}}

        把 N 次逐条 update 合并成 1 条 UPDATE ... FROM (VALUES ...) · 1 次网络往返 ·
        写放大从 O(N/周期) 降到 O(1/周期) · 这是打破单进程 ~1.4k 节点封顶的关键。
        同 update_heartbeat 一并设 status=ONLINE (节点仍 hb → 从 reaper OFFLINE 自动恢复)。
        分块 2000/批 防超 PG 65535 绑定参数上限。
        """
        if not buffer:
            return 0
        from sqlalchemy import text
        items = list(buffer.items())
        total = 0
        CHUNK = 2000
        for start in range(0, len(items), CHUNK):
            chunk = items[start:start + CHUNK]
            rows = []
            params: dict = {}
            for i, (wid, v) in enumerate(chunk):
                rows.append(f"(CAST(:id{i} AS uuid), CAST(:ls{i} AS timestamp), :ld{i}, :ac{i})")
                params[f"id{i}"] = wid
                params[f"ls{i}"] = v["last_seen"]
                params[f"ld{i}"] = float(v.get("load") or 0.0)
                params[f"ac{i}"] = int(v.get("active_shards") or 0)
            sql = (
                "UPDATE we_workers AS w SET "
                "last_seen = v.ls, load = v.ld, active_shards = v.ac, status = 'ONLINE' "
                f"FROM (VALUES {','.join(rows)}) AS v(id, ls, ld, ac) "
                "WHERE w.id = v.id "
                "AND (w.disabled_until IS NULL OR w.disabled_until <= CURRENT_TIMESTAMP)"
            )
            result = s.execute(text(sql), params)
            total += result.rowcount or 0
        return total

