# ApiKeyRepo · 企业开发者长期 API Key (we_api_keys · v8_031)
# 明文 qs_<32hex> 仅创建时返回一次 · DB 只存 sha256
# ════════════════════════════════════════════════════════════════════
API_KEY_PREFIX = "qs_"
API_KEY_MAX_PER_ACCOUNT = 10
API_KEY_DEFAULT_SCOPES = ["files", "workloads", "results", "webhooks"]
API_KEY_ALLOWED_SCOPES = frozenset({*API_KEY_DEFAULT_SCOPES, "*"})
_API_KEY_TOUCH_TTL_S = max(60, int(os.environ.get("V8_API_KEY_TOUCH_TTL_S", "300")))
_api_key_touch_lock = threading.Lock()
_api_key_touch_local: dict[int, float] = {}


def _hash_api_key(secret: str) -> str:
    import hashlib
    return hashlib.sha256(secret.encode("utf-8")).hexdigest()


def _should_touch_api_key(key_id: int) -> bool:
    """每个 Key 每个时间窗只回写一次，避免并发鉴权争抢同一行锁。"""
    try:
        from platform_v8.storage.kv import get_redis

        redis = get_redis()
        if redis is not None:
            return bool(
                redis.set(
                    f"v8:auth:api-key-touch:{key_id}",
                    "1",
                    ex=_API_KEY_TOUCH_TTL_S,
                    nx=True,
                )
            )
    except Exception:
        # Redis 不可用时退化为进程内节流；功能与鉴权结果不受影响。
        pass

    now = time.monotonic()
    with _api_key_touch_lock:
        previous = _api_key_touch_local.get(key_id, 0.0)
        if now - previous < _API_KEY_TOUCH_TTL_S:
            return False
        _api_key_touch_local[key_id] = now
        if len(_api_key_touch_local) > 10_000:
            cutoff = now - _API_KEY_TOUCH_TTL_S
            stale = [
                item_id
                for item_id, touched_at in _api_key_touch_local.items()
                if touched_at < cutoff
            ]
            for item_id in stale:
                _api_key_touch_local.pop(item_id, None)
        return True


def _utc_now() -> datetime:
    return datetime.now(timezone.utc)


def _as_utc(value: datetime | None) -> datetime | None:
    """PG 返回 aware，SQLite/旧测试数据可能是 naive；统一按 UTC 比较。"""
    if value is None:
        return None
    if value.tzinfo is None:
        return value.replace(tzinfo=timezone.utc)
    return value.astimezone(timezone.utc)


def _effective_api_key_scopes(raw: Any) -> list[str]:
    if isinstance(raw, str):
        try:
            raw = json.loads(raw or "[]")
        except (TypeError, json.JSONDecodeError):
            return []
    if raw is None or raw == []:
        # 存量空 scopes Key 保持 wildcard；新 Key 由 create 写入显式默认 scopes。
        return ["*"]
    if not isinstance(raw, list):
        return []
    scopes = [str(scope).strip().lower() for scope in raw if str(scope).strip()]
    return list(dict.fromkeys(scopes)) or ["*"]


def _row_to_api_key(row, *, include_secret: bool = False, secret: str | None = None) -> dict:
    out = {
        "id": int(row.id),
        "account_id": int(row.account_id),
        "name": row.name or "",
        "key_prefix": row.key_prefix,
        "scopes": _effective_api_key_scopes(row.scopes),
        "last_used_at": row.last_used_at.isoformat() if row.last_used_at else None,
        "expires_at": row.expires_at.isoformat() if row.expires_at else None,
        "revoked": bool(row.revoked),
        "revoked_at": row.revoked_at.isoformat() if row.revoked_at else None,
        "created_at": row.created_at.isoformat() if row.created_at else None,
    }
    if include_secret and secret:
        out["secret_once"] = secret
    return out


class ApiKeyRepo:
    """开发者 API Key CRUD + 鉴权查找。"""

    @staticmethod
    def generate_secret() -> tuple[str, str]:
        """返回 (完整明文 key, 展示用前缀 qs_xxxxxx)。"""
        import secrets
        raw = secrets.token_hex(16)
        secret = f"{API_KEY_PREFIX}{raw}"
        prefix = f"{API_KEY_PREFIX}{raw[:6]}"
        return secret, prefix

    @staticmethod
    def count_active(s: Session, account_id: int) -> int:
        now = _utc_now()
        n = s.execute(
            select(func.count())
            .select_from(api_keys_t)
            .where(
                api_keys_t.c.account_id == account_id,
                api_keys_t.c.revoked.is_(False),
                or_(
                    api_keys_t.c.expires_at.is_(None),
                    api_keys_t.c.expires_at > now,
                ),
            )
        ).scalar()
        return int(n or 0)

    @staticmethod
    def list_for_account(s: Session, account_id: int, *, include_revoked: bool = False) -> list[dict]:
        q = select(api_keys_t).where(api_keys_t.c.account_id == account_id)
        if not include_revoked:
            q = q.where(api_keys_t.c.revoked.is_(False))
        q = q.order_by(api_keys_t.c.created_at.desc())
        rows = s.execute(q).fetchall()
        return [_row_to_api_key(r) for r in rows]

    @staticmethod
    def create(
        s: Session,
        *,
        account_id: int,
        name: str = "",
        scopes: list[str] | None = None,
        expires_days: int | None = None,
    ) -> dict:
        secret, prefix = ApiKeyRepo.generate_secret()
        now = _utc_now()
        expires_at = None
        if expires_days is not None:
            expires_at = now + timedelta(days=int(expires_days))
        result = s.execute(
            insert(api_keys_t)
            .values(
                account_id=account_id,
                name=(name or "")[:100],
                key_prefix=prefix,
                key_sha256=_hash_api_key(secret),
                scopes=(
                    list(dict.fromkeys(
                        str(scope).strip().lower()
                        for scope in scopes
                        if str(scope).strip()
                    ))
                    if scopes
                    else list(API_KEY_DEFAULT_SCOPES)
                ),
                expires_at=expires_at,
                revoked=False,
                created_at=now,
            )
            .returning(api_keys_t)
        )
        row = result.one()
        s.flush()
        return _row_to_api_key(row, include_secret=True, secret=secret)

    @staticmethod
    def revoke(s: Session, *, key_id: int, account_id: int) -> bool:
        result = s.execute(
            update(api_keys_t)
            .where(
                api_keys_t.c.id == key_id,
                api_keys_t.c.account_id == account_id,
                api_keys_t.c.revoked.is_(False),
            )
            .values(revoked=True, revoked_at=_utc_now())
        )
        return result.rowcount > 0

    @staticmethod
    def resolve_account(s: Session, secret: str) -> Account | None:
        """兼容旧调用方；新鉴权应使用 resolve_key 同时取得真实 scopes。"""
        account, _ = ApiKeyRepo.resolve_key(s, secret)
        return account

    @staticmethod
    def resolve_key(s: Session, secret: str) -> tuple[Account | None, list[str]]:
        """解析 API Key 与有效 scopes；无效/吊销/过期返回 ``(None, [])``。"""
        if not secret or not (
            secret.startswith(API_KEY_PREFIX) or secret.startswith("qsk_")
        ):
            return None, []
        digest = _hash_api_key(secret)
        row = s.execute(
            select(api_keys_t).where(
                api_keys_t.c.key_sha256 == digest,
                api_keys_t.c.revoked.is_(False),
            )
        ).one_or_none()
        if row is None:
            return None, []
        now = _utc_now()
        expires_at = _as_utc(row.expires_at)
        if expires_at is not None and expires_at <= now:
            return None, []
        if _should_touch_api_key(int(row.id)):
            s.execute(
                update(api_keys_t)
                .where(api_keys_t.c.id == row.id)
                .values(last_used_at=now)
            )
        account = AccountRepo.by_id(s, int(row.account_id))
        if account is None:
            return None, []
        return account, _effective_api_key_scopes(row.scopes)


