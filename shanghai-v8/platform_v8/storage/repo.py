    @staticmethod
    def record_result_upload_issuance(
        s: Session,
        shard_id: str,
        *,
        worker_id: str,
        object_key: str,
        result_id: str,
        size_bytes: int,
        sha256: str,
        content_type: str,
        expires_at: int | None = None,
        expected_attempt: int | None = None,
    ) -> bool:
        """Persist one artifact issuance per active shard attempt.

        Repeating the same request is safe and lets a worker recover from a
        transient failed PUT.  A different active request is rejected rather
        than orphaning the first object or silently changing the accepted
        manifest.
        """
        row = s.execute(
            select(shards_t.c.metadata, shards_t.c.attempts)
            .where(shards_t.c.id == shard_id)
            .where(shards_t.c.status.in_([
                ShardStatus.DISPATCHED.value,
                ShardStatus.RUNNING.value,
                ShardStatus.LEASED.value,
            ]))
            .with_for_update()
        ).first()
        if row is None:
            return False
        if (
            expected_attempt is not None
            and int(row.attempts or 0) != int(expected_attempt)
        ):
            return False
        metadata = dict(row.metadata or {})
        current = ShardRepo.by_id(s, shard_id)
        if current is None or str(worker_id) not in ShardRepo.race_workers_of(current):
            return False
        issuance = {
            "worker_id": str(worker_id),
            "attempt": int(row.attempts or 0),
            "object_key": str(object_key),
            "result_id": str(result_id),
            "size_bytes": int(size_bytes),
            "sha256": str(sha256).lower(),
            "content_type": str(content_type),
            "expires_at": int(expires_at or 0),
        }
        issuances = dict(metadata.get("result_upload_issuances") or {})
        existing = issuances.get(str(worker_id))
        # Preserve the pre-race storage shape for the owner so already-issued
        # clients remain compatible, while racers receive independent bindings.
        if existing is None and metadata.get("result_upload_issuance", {}).get("worker_id") == str(worker_id):
            existing = metadata["result_upload_issuance"]
        comparable = (
            "worker_id", "attempt", "object_key", "result_id", "size_bytes",
            "sha256", "content_type",
        )
        if isinstance(existing, dict):
            if all(existing.get(key) == issuance[key] for key in comparable):
                return True
            return False
        issuances[str(worker_id)] = issuance
        metadata["result_upload_issuances"] = issuances
        if str(worker_id) == str(current.worker_id):
            metadata["result_upload_issuance"] = issuance
        result = s.execute(
            update(shards_t)
            .where(shards_t.c.id == shard_id)
            .where(shards_t.c.attempts == int(row.attempts or 0))
            .where(shards_t.c.status.in_([
                ShardStatus.DISPATCHED.value,
                ShardStatus.RUNNING.value,
                ShardStatus.LEASED.value,
            ]))
            .values(metadata=metadata)
        )
        return result.rowcount > 0

