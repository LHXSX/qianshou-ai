    @staticmethod
    def by_fingerprint_for_account(
        s: Session,
        account_id: int,
        fingerprint: str,
    ) -> dict | None:
        """按客户端持久化指纹找回同一物理设备（不依赖 cookie）。"""
        fp = str(fingerprint or "").strip()
        if not fp or len(fp) > 128:
            return None
        for row in TrustedDeviceRepo.list_for_account(s, account_id):
            meta = row.get("metadata") or {}
            if isinstance(meta, str):
                try:
                    meta = json.loads(meta)
                except Exception:
                    meta = {}
            if str(meta.get("fingerprint") or "").strip() == fp:
                return row
        return None

    @staticmethod
    def rotate_credential(
        s: Session,
        device_id: str,
        account_id: int,
        credential_hash: str,
        metadata_value: dict | None = None,
    ) -> dict | None:
        values: dict[str, Any] = {
            "credential_hash": credential_hash,
            "last_seen_at": datetime.utcnow(),
        }
        if metadata_value is not None:
            values["metadata"] = metadata_value
        result = s.execute(
            update(auth_devices_t)
            .where(
                auth_devices_t.c.id == device_id,
                auth_devices_t.c.account_id == account_id,
            )
            .values(**values)
        )
        if result.rowcount <= 0:
            return None
        return TrustedDeviceRepo.by_id_for_account(s, device_id, account_id)

    @staticmethod
    def delete_orphans(s: Session, account_id: int, *, keep_device_ids: set[str]) -> int:
        """删除账户下已无会话引用、且不在保留集合中的设备行。"""
        keep = {str(x) for x in keep_device_ids if x}
        referenced = {
            str(r[0])
            for r in s.execute(
                select(auth_sessions_t.c.device_id)
                .where(
                    auth_sessions_t.c.account_id == account_id,
                    auth_sessions_t.c.device_id.is_not(None),
                )
                .distinct()
            ).all()
            if r[0]
        }
        victims = []
        for row in TrustedDeviceRepo.list_for_account(s, account_id):
            did = str(row["id"])
            if did in keep or did in referenced:
                continue
            victims.append(did)
        if not victims:
            return 0
        result = s.execute(
            delete(auth_devices_t).where(
                auth_devices_t.c.account_id == account_id,
                auth_devices_t.c.id.in_(victims),
            )
        )
        return int(result.rowcount or 0)

    @staticmethod
    def touch(
        s: Session,
        device_id: str,
        account_id: int,
        metadata_value: dict,
    ) -> bool:
        # 合并旧 metadata，避免覆盖已有 fingerprint
        existing = TrustedDeviceRepo.by_id_for_account(s, device_id, account_id)
        merged = {}
        if existing:
            old = existing.get("metadata") or {}
            if isinstance(old, str):
                try:
                    old = json.loads(old)
                except Exception:
                    old = {}
            if isinstance(old, dict):
                merged.update(old)
        if isinstance(metadata_value, dict):
            merged.update({k: v for k, v in metadata_value.items() if v is not None})
        result = s.execute(
            update(auth_devices_t)
            .where(
                auth_devices_t.c.id == device_id,
                auth_devices_t.c.account_id == account_id,
            )
            .values(metadata=merged, last_seen_at=datetime.utcnow())
        )
        return result.rowcount > 0

