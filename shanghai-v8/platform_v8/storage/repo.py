    # ════════════════════════════════════════════════════════════════
    # W1 (2026-05-26) · 统一引擎 · PULL 模式 lease 操作
    # ════════════════════════════════════════════════════════════════
    @staticmethod
    def lease_pending_pull(
        s: Session, *,
        worker_id: str,
        max_count: int = 1,
        task_type_filter: list[str] | None = None,
        lease_seconds: int | None = None,
        lease_seconds_for: Callable[[Shard], int] | None = None,
    ) -> list[Shard]:
        """PULL 模式 · 节点抢 N 条 PENDING shard
        
        FOR UPDATE SKIP LOCKED 防并发抢 · 写 status=LEASED + lease_by_node + lease_expires_at
        
        W4-phase2 (2026-05-26) · 同节点 anti-replica 排除:
          若 shard.metadata.replica_of IS NOT NULL (= 冗余业务 · verify_level=2 等)
          排除同 worker 已 lease/done 过的同 canonical 的副本
          → 保证一片冗余必须不同节点跑 (anti_cheat 多数派比对前提)
        
        Args:
            worker_id: 抢任务的节点 ID
            max_count: 单次最多抢几条
            task_type_filter: 节点想要的 task_type 列表 (空=任意)
            lease_seconds: 显式固定租约（兼容管理/测试调用）
            lease_seconds_for: 按分片计算租约；正常 PULL 路径必须传入
        
        Returns:
            被 lease 走的 Shard 列表 (已是 LEASED 状态)
        """
        from datetime import timedelta
        from sqlalchemy import text as _sql_text

        # 最靠近抢占事务的防线：临时禁用节点不能 lease 新分片。
        blocked = s.execute(
            select(workers_t.c.id)
            .where(workers_t.c.id == worker_id)
            .where(workers_t.c.disabled_until > func.now())
        ).first()
        if blocked:
            return []
        capabilities = s.execute(select(workers_t.c.capabilities).where(
            workers_t.c.id == worker_id)).scalar_one_or_none()
        if isinstance(capabilities, dict) and capabilities.get("review_only") is True:
            # Dedicated audit workers never claim a paid PULL shard, even if
            # the optional capability feature flag is disabled.
            return []
        
        # W4-phase2 · 同节点 anti-replica · 用 raw SQL (JSON metadata 跨方言难统一)
        # 用 raw SQL 子查询排除 · postgres 专用 · 配合 metadata::jsonb 操作符
        # SQLite 测试时 metadata 是 JSON 列 (sqlalchemy 自动序列化) · NOT EXISTS 部分会被 PG 优化器 short-circuit
        # NOT EXISTS 子查询: 排除存在另一片同 canonical 已被本节点 lease 的 shard
        # 注 · PG JSON 列原生支持 ->> · 不需 CAST
        # SQLite (测试用) 没 ->> · 但本函数走 mock · raw SQL 不实际执行
        anti_replica_clause = _sql_text(
            "NOT EXISTS ("
            "  SELECT 1 FROM we_shards other "
            "  WHERE other.workload_id = we_shards.workload_id "
            "    AND other.lease_by_node = :__worker_id_anti "
            "    AND other.id <> we_shards.id "
            "    AND COALESCE(other.metadata->>'replica_of', '') != '' "
            "    AND (other.metadata->>'replica_of') = (we_shards.metadata->>'replica_of')"
            ")"
        ).bindparams(__worker_id_anti=worker_id)

        # 定向派发的 SQL 防线：PULL 节点只能租到白名单中的 workload。
        allowed_worker_clause = _sql_text(
            "("
            "  (we_workloads.spec->'requirements'->'allowed_worker_ids') IS NULL"
            "  OR (we_workloads.spec->'requirements'->'allowed_worker_ids')::jsonb = '[]'::jsonb"
            "  OR (we_workloads.spec->'requirements'->'allowed_worker_ids') ? :__allowed_worker_id"
            ")"
        ).bindparams(__allowed_worker_id=worker_id)
        
        # 子查询: 拿 N 条 PENDING + mode=PULL · FOR UPDATE SKIP LOCKED
        # task_type 在 workloads_t.spec 里 (JSON.task_type) · 加 join + filter
        if task_type_filter:
            # join workloads_t · spec JSON 取 task_type
            subq = (
                select(shards_t.c.id)
                .select_from(shards_t.join(workloads_t, workloads_t.c.id == shards_t.c.workload_id))
                .where(shards_t.c.status == ShardStatus.PENDING.value)
                .where(shards_t.c.mode == ShardMode.PULL.value)
                .where(func.coalesce(shards_t.c.exec_attempts, 0) < shards_t.c.max_attempts)
                # spec JSON 取 task_type · postgres 用 ->> 操作符 (SQLite 兼容差但 PULL 主要跑生产 PG)
                .where(_sql_text("(we_workloads.spec->>'task_type') = ANY(:tt)"))
                .where(allowed_worker_clause)
                .where(anti_replica_clause)
                .order_by(shards_t.c.score.desc(), shards_t.c.index)
                .limit(max_count)
                .with_for_update(skip_locked=True, of=shards_t)
            )
            picked = s.execute(subq, {"tt": task_type_filter}).scalars().all()
        else:
            subq = (
                select(shards_t.c.id)
                .select_from(shards_t.join(workloads_t, workloads_t.c.id == shards_t.c.workload_id))
                .where(shards_t.c.status == ShardStatus.PENDING.value)
                .where(shards_t.c.mode == ShardMode.PULL.value)
                .where(func.coalesce(shards_t.c.exec_attempts, 0) < shards_t.c.max_attempts)
                .where(allowed_worker_clause)
                .where(anti_replica_clause)
                .order_by(shards_t.c.score.desc(), shards_t.c.index)
                .limit(max_count)
                .with_for_update(skip_locked=True)
            )
            picked = s.execute(subq).scalars().all()
        
        if not picked:
            return []

        if lease_seconds is None and lease_seconds_for is None:
            raise ValueError(
                "lease_pending_pull requires lease_seconds_for or explicit lease_seconds"
            )

        # The selected rows are locked, so each conditional update below issues
        # the exact incremented attempt while clearing any prior lease/artifact
        # binding before its next owner receives a token.
        selected_rows = s.execute(
            select(shards_t).where(shards_t.c.id.in_(picked))
        ).all()
        selected = {row.id: _row_to_shard(row) for row in selected_rows}
        now = datetime.utcnow()
        for shard_id in picked:
            selected_shard = selected[shard_id]
            ttl = (
                int(lease_seconds_for(selected_shard))
                if lease_seconds_for is not None
                else int(lease_seconds or 0)
            )
            if ttl <= 0:
                raise ValueError(
                    f"invalid pull lease ttl={ttl} for shard={shard_id}"
                )
            s.execute(
                update(shards_t)
                .where(shards_t.c.id == shard_id)
                .where(shards_t.c.status == ShardStatus.PENDING.value)
                .values(
                    status=ShardStatus.LEASED.value,
                    worker_id=None,
                    lease_by_node=worker_id,
                    lease_expires_at=now + timedelta(seconds=ttl),
                    attempts=shards_t.c.attempts + 1,
                    dispatch_attempts=func.coalesce(shards_t.c.dispatch_attempts, 0) + 1,
                    dispatched_at=now,
                    started_at=None,
                    progress_at=None,
                    completed_at=None,
                    metadata=_clear_attempt_bindings(selected_shard.metadata),
                )
            )
        
        # 返回 Shard 列表 (已包含 LEASED status)
        rows = s.execute(
            select(shards_t).where(shards_t.c.id.in_(picked))
        ).all()
        return [_row_to_shard(r) for r in rows]

    @staticmethod
    def confirm_lease_start(
        s: Session,
        shard_id: str,
        *,
        expected_worker_id: str,
        expected_attempt: int,
        lease_seconds: int,
    ) -> bool:
        """PULL 模式 · 节点收到 PullAssign 后 ack 开跑 · LEASED → RUNNING
        
        CAS 校验 lease_by_node == expected_worker_id (防别的节点冒充)
        """
        result = s.execute(
            update(shards_t)
            .where(shards_t.c.id == shard_id)
            .where(shards_t.c.status == ShardStatus.LEASED.value)
            .where(shards_t.c.lease_by_node == expected_worker_id)
            .where(shards_t.c.attempts == int(expected_attempt))
            .values(
                status=ShardStatus.RUNNING.value,
                worker_id=expected_worker_id,
                started_at=datetime.utcnow(),
                lease_expires_at=datetime.utcnow() + timedelta(
                    seconds=max(1, int(lease_seconds))
                ),
                exec_attempts=func.coalesce(shards_t.c.exec_attempts, 0) + 1,
            )
        )
        return result.rowcount > 0

    @staticmethod
    def release_lease(s: Session, shard_id: str, *, expected_worker_id: str | None = None) -> bool:
        """PULL 模式 · 节点主动放弃 lease · LEASED → PENDING
        
        Args:
            expected_worker_id: CAS 校验 (None = 不校验 · sweeper 用)
        """
        shard = ShardRepo.by_id(s, shard_id)
        if shard is None:
            return False
        stmt = (
            update(shards_t)
            .where(shards_t.c.id == shard_id)
            .where(shards_t.c.status == ShardStatus.LEASED.value)
        )
        if expected_worker_id is not None:
            stmt = stmt.where(shards_t.c.lease_by_node == expected_worker_id)
        result = s.execute(
            stmt.values(
                status=ShardStatus.PENDING.value,
                worker_id=None,
                dispatched_at=None,
                started_at=None,
                lease_by_node=None,
                lease_expires_at=None,
                progress_at=None,
                metadata=_clear_attempt_bindings(shard.metadata),
            )
        )
        return result.rowcount > 0

    @staticmethod
    def reap_expired_leases(s: Session, *, limit: int = 100) -> int:
        """PULL 模式 · 把 lease 过期的 shard 回 PENDING (sweeper 定期调)

        2026-06-06 · 扩展回收 RUNNING:
          confirm_lease_start 把 PULL shard 置 RUNNING(保留 lease_expires_at)·若节点 confirm 后崩,
          RUNNING shard 也会因 lease_expires_at 超时被回收。
          ONESHOT 的 RUNNING 不设 lease_expires_at(NULL)·`lease_expires_at < now` 对 NULL 不命中 → 不误收。

        Returns:
            释放数量
        """
        now = datetime.utcnow()
        # 仅回收带 lease_expires_at(即 PULL)且过期的 LEASED/RUNNING · ONESHOT(lease_expires_at=NULL)不受影响
        rows = s.execute(
            select(shards_t.c.id, shards_t.c.metadata)
            .where(shards_t.c.status.in_([ShardStatus.LEASED.value, ShardStatus.RUNNING.value]))
            .where(shards_t.c.lease_expires_at.isnot(None))
            .where(shards_t.c.lease_expires_at < now)
            .limit(limit)
        ).all()
        if not rows:
            return 0
        reaped = 0
        for row in rows:
            result = s.execute(
                update(shards_t)
                .where(shards_t.c.id == row.id)
                .where(shards_t.c.status.in_([
                    ShardStatus.LEASED.value,
                    ShardStatus.RUNNING.value,
                ]))
                .where(shards_t.c.lease_expires_at < now)
                .values(
                    status=ShardStatus.PENDING.value,
                    lease_by_node=None,
                    lease_expires_at=None,
                    worker_id=None,
                    dispatched_at=None,
                    started_at=None,
                    progress_at=None,
                    metadata=_clear_attempt_bindings(row.metadata),
                )
            )
            reaped += result.rowcount
        return reaped


