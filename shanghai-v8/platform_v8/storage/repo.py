    @staticmethod
    def upsert(
        s: Session,
        *,
        worker_id: str,
        owner_id: int,
        name: str,
        capabilities: dict,
        client_version: str = "",
        client_build: str | None = None,
        protocol_capabilities: list[str] | None = None,
        legacy_protocol: bool | None = None,
        status: WorkerStatus = WorkerStatus.ONLINE,
    ) -> Worker:
        """
        注册 / 重连用 · 同 worker_id 二次调用 = update。

        全程 1 个语句 (Postgres ON CONFLICT · SQLite INSERT OR REPLACE 由 SQLAlchemy 处理)
        但 SQLAlchemy Core 没有跨方言的 UPSERT · 这里用"先查后写"实现 (业务 OK)。
        """
        now = datetime.utcnow()
        capabilities = dict(capabilities or {})
        if legacy_protocol is not None and client_build is None:
            capabilities.pop("client_build", None)
        if legacy_protocol is not None and protocol_capabilities is None:
            capabilities.pop("protocol_capabilities", None)
        if client_build is not None:
            capabilities["client_build"] = str(client_build)[:128]
        if protocol_capabilities is not None:
            capabilities["protocol_capabilities"] = list(dict.fromkeys(
                str(item).strip().lower()
                for item in protocol_capabilities
                if str(item).strip()
            ))[:32]
        if legacy_protocol is not None:
            capabilities["protocol_legacy"] = bool(legacy_protocol)
        # v8.1.8 · 同步 capability_score 列 = 客户端 bench 跑分 (capabilities.bench_capability_score)
        # 此前此列恒 0,导致 planner NCE 排序的 +10×cap/100 维度对所有节点白算。
        # 上线/重连时从 hello 的 capabilities 刷新 (bench 客户端启动时算一次)
        cap_score = 0.0
        try:
            cap_score = float((capabilities or {}).get("bench_capability_score", 0) or 0)
        except (TypeError, ValueError):
            cap_score = 0.0
        existing = WorkerRepo.by_id(s, worker_id)
        # review_only is an operator-owned isolation bit, never a client hello
        # declaration. Preserve it across reconnects, and reject self-marking
        # by a newly registered worker.
        capabilities.pop("review_only", None)
        if existing is not None and existing.capabilities.review_only:
            capabilities["review_only"] = True
        if existing is None:
            s.execute(
                insert(workers_t).values(
                    id=worker_id,
                    owner_id=owner_id,
                    name=name,
                    status=status.value,
                    capabilities=capabilities,
                    load=0.0,
                    active_shards=0,
                    reputation=0.5,
                    capability_score=cap_score,
                    last_seen=now,
                    registered_at=now,
                    client_version=client_version,
                )
            )
        else:
            # update 不动 registered_at + reputation (历史信用)
            # capability_score 随 bench 刷新 (但仅当上报了有效值 · 否则保留旧值不清零)
            _update_vals = dict(
                owner_id=owner_id,
                name=name,
                status=status.value,
                capabilities=capabilities,
                last_seen=now,
                client_version=client_version,
            )
            if cap_score > 0:
                _update_vals["capability_score"] = cap_score
            s.execute(
                update(workers_t)
                .where(workers_t.c.id == worker_id)
                .values(**_update_vals)
            )
        s.flush()
        result = WorkerRepo.by_id(s, worker_id)
        if result is None:
            raise RuntimeError(f"upsert worker failed · id={worker_id}")
        return result

