def unknown_capability_fields(capabilities: dict[str, Any] | None) -> list[str]:
    """返回 capabilities 里平台无人读取的键（排序）。空列表 = 全部已知。"""
    if not capabilities:
        return []
    known = {f.name for f in dc_fields(WorkerCapabilities)} | _CAPABILITY_KEYS_READ_ELSEWHERE
    unknown_fields = sorted(str(k) for k in capabilities.keys() if str(k) not in known)
    return unknown_fields


