class VerifierCircuitRepo:
    """Transaction-friendly durable circuit state keyed by verifier."""

    CLOSED = "closed"
    OPEN = "open"
    HALF_OPEN = "half_open"

    @staticmethod
    def get(s: Session, verifier_key: str) -> dict[str, Any] | None:
        row = s.execute(
            select(verifier_circuits_t).where(
                verifier_circuits_t.c.verifier_key == str(verifier_key)
            )
        ).one_or_none()
        return _row_dict(row)

    @staticmethod
    def record_success(
        s: Session,
        verifier_key: str,
        *,
        expected_state: str | None = None,
        now: datetime | None = None,
    ) -> bool:
        key = str(verifier_key or "").strip()
        if not key:
            raise ValueError("verifier_key is required")
        recorded_at = now or datetime.now(timezone.utc)
        stmt = update(verifier_circuits_t).where(
            verifier_circuits_t.c.verifier_key == key,
            verifier_circuits_t.c.state.in_([
                VerifierCircuitRepo.CLOSED,
                VerifierCircuitRepo.HALF_OPEN,
            ]),
        )
        if expected_state is not None:
            stmt = stmt.where(verifier_circuits_t.c.state == str(expected_state))
        result = s.execute(
            stmt.values(
                state=VerifierCircuitRepo.CLOSED,
                consecutive_failures=0,
                opened_until=None,
                probe_lease_until=None,
                updated_at=recorded_at,
            )
        )
        if result.rowcount > 0:
            return True
        if VerifierCircuitRepo.get(s, key) is not None:
            return False
        try:
            with s.begin_nested():
                s.execute(
                    insert(verifier_circuits_t).values(
                        verifier_key=key,
                        state=VerifierCircuitRepo.CLOSED,
                        consecutive_failures=0,
                        updated_at=recorded_at,
                    )
                )
            return True
        except IntegrityError:
            return False

    @staticmethod
    def record_failure(
        s: Session,
        verifier_key: str,
        *,
        failure_threshold: int = 3,
        cooldown_seconds: int = 60,
        now: datetime | None = None,
    ) -> dict[str, Any]:
        key = str(verifier_key or "").strip()
        if not key:
            raise ValueError("verifier_key is required")
        threshold = max(1, int(failure_threshold))
        recorded_at = now or datetime.now(timezone.utc)
        row = s.execute(
            select(verifier_circuits_t)
            .where(verifier_circuits_t.c.verifier_key == key)
            .with_for_update()
        ).one_or_none()
        if row is None:
            failures = 1
            state = (
                VerifierCircuitRepo.OPEN
                if failures >= threshold
                else VerifierCircuitRepo.CLOSED
            )
            try:
                with s.begin_nested():
                    s.execute(
                        insert(verifier_circuits_t).values(
                            verifier_key=key,
                            state=state,
                            consecutive_failures=failures,
                            opened_until=(
                                recorded_at + timedelta(seconds=max(1, int(cooldown_seconds)))
                                if state == VerifierCircuitRepo.OPEN
                                else None
                            ),
                            probe_lease_until=None,
                            updated_at=recorded_at,
                        )
                    )
            except IntegrityError:
                # Retry against the row created by the concurrent transaction.
                return VerifierCircuitRepo.record_failure(
                    s,
                    key,
                    failure_threshold=threshold,
                    cooldown_seconds=cooldown_seconds,
                    now=recorded_at,
                )
        else:
            failures = int(row.consecutive_failures or 0) + 1
            should_open = (
                row.state in (VerifierCircuitRepo.OPEN, VerifierCircuitRepo.HALF_OPEN)
                or failures >= threshold
            )
            state = VerifierCircuitRepo.OPEN if should_open else VerifierCircuitRepo.CLOSED
            result = s.execute(
                update(verifier_circuits_t)
                .where(
                    verifier_circuits_t.c.verifier_key == key,
                    verifier_circuits_t.c.state == row.state,
                    verifier_circuits_t.c.consecutive_failures
                    == int(row.consecutive_failures or 0),
                    verifier_circuits_t.c.updated_at == row.updated_at,
                )
                .values(
                    state=state,
                    consecutive_failures=failures,
                    opened_until=(
                        recorded_at + timedelta(seconds=max(1, int(cooldown_seconds)))
                        if should_open
                        else None
                    ),
                    probe_lease_until=None,
                    updated_at=recorded_at,
                )
            )
            if result.rowcount <= 0:
                raise RuntimeError("verifier circuit failure CAS lost")
        persisted = VerifierCircuitRepo.get(s, key)
        if persisted is None:
            raise RuntimeError("verifier circuit failure was not persisted")
        return persisted

    @staticmethod
    def claim_half_open(
        s: Session,
        verifier_key: str,
        *,
        lease_seconds: int = 60,
        now: datetime | None = None,
    ) -> dict[str, Any] | None:
        key = str(verifier_key or "").strip()
        if not key:
            raise ValueError("verifier_key is required")
        claimed_at = now or datetime.now(timezone.utc)
        eligible = or_(
            and_(
                verifier_circuits_t.c.state == VerifierCircuitRepo.OPEN,
                verifier_circuits_t.c.opened_until.is_not(None),
                verifier_circuits_t.c.opened_until <= claimed_at,
            ),
            and_(
                verifier_circuits_t.c.state == VerifierCircuitRepo.HALF_OPEN,
                or_(
                    verifier_circuits_t.c.probe_lease_until.is_(None),
                    verifier_circuits_t.c.probe_lease_until <= claimed_at,
                ),
            ),
        )
        result = s.execute(
            update(verifier_circuits_t)
            .where(verifier_circuits_t.c.verifier_key == key)
            .where(eligible)
            .values(
                state=VerifierCircuitRepo.HALF_OPEN,
                opened_until=None,
                probe_lease_until=claimed_at + timedelta(
                    seconds=max(1, int(lease_seconds))
                ),
                updated_at=claimed_at,
            )
        )
        return VerifierCircuitRepo.get(s, key) if result.rowcount > 0 else None


